/// ¿El punto está dentro de Bolivia? Usa el contorno oficial simplificado
/// (GeoBolivia vía geoBoundaries, ~1 km de precisión en la frontera), así que
/// un punto a pocos cientos de metros del límite puede caer de cualquier lado.
bool isInBolivia(double latitude, double longitude) {
  var inside = false;
  for (var i = 0, j = _outline.length - 1; i < _outline.length; j = i++) {
    final (yi, xi) = _outline[i];
    final (yj, xj) = _outline[j];
    if ((yi > latitude) != (yj > latitude) && longitude < (xj - xi) * (latitude - yi) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/// Distancia en km entre dos puntos (fórmula del semiverseno).
double kmBetween(double lat1, double lng1, double lat2, double lng2) {
  const r = 6371.0;
  double rad(double d) => d * math.pi / 180;
  final dLat = rad(lat2 - lat1);
  final dLng = rad(lng2 - lng1);
  final a =
      math.pow(math.sin(dLat / 2), 2) + math.cos(rad(lat1)) * math.cos(rad(lat2)) * math.pow(math.sin(dLng / 2), 2);
  return 2 * r * math.asin(math.sqrt(a));
}

/// El municipio cuya coordenada de referencia está más cerca del punto. Es una
/// sugerencia: en municipios grandes la persona puede corregirla.
City? nearestCity(List<City> cities, double latitude, double longitude) {
  City? best;
  var bestKm = double.infinity;
  for (final c in cities) {
    if (c.latitude == null || c.longitude == null) continue;
    final km = kmBetween(latitude, longitude, c.latitude!, c.longitude!);
    if (km < bestKm) {
      bestKm = km;
      best = c;
    }
  }
  return best;
}

